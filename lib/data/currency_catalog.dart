class CurrencyInfo {
  const CurrencyInfo(this.code, this.name, this.symbol, this.flag);
  final String code;
  final String name;
  final String symbol;
  final String flag;
}


String flagFromCountry(String cc) => String.fromCharCodes(
      cc.toUpperCase().codeUnits.map((u) => 0x1F1E6 + (u - 0x41)),
    );


